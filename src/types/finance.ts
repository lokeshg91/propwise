/**
 * Finance records (save format v5). Amounts are integer minor units (cents)
 * in the currency set in `FinanceSettings`. Calendar dates are YYYY-MM-DD,
 * periods are YYYY-MM and `createdAt`/`updatedAt` are ISO timestamps.
 * Optional fields are omitted rather than stored as null to keep records small.
 *
 * Records are local demo/application data: Propwise doesn't process payments.
 */

export const INCOME_CATEGORIES = ['rent', 'late-fee', 'parking', 'service-charge', 'utility-recovery', 'other-income'] as const
export type IncomeCategory = (typeof INCOME_CATEGORIES)[number]

/** Income categories a recurring schedule can bill. Rent comes from the lease itself. */
export const RECURRING_CATEGORIES = ['parking', 'service-charge', 'utility-recovery', 'other-income'] as const
export type RecurringCategory = (typeof RECURRING_CATEGORIES)[number]

export const EXPENSE_CATEGORIES = [
  'maintenance',
  'utilities',
  'insurance',
  'property-tax',
  'management-fee',
  'cleaning',
  'landscaping',
  'security',
  'pest-control',
  'supplies',
  'other-expense',
] as const
export type ExpenseCategory = (typeof EXPENSE_CATEGORIES)[number]

/** How money moved. Labels only — nothing is processed. */
export const PAYMENT_METHODS = ['bank-transfer', 'card', 'check', 'cash', 'other'] as const
export type PaymentMethod = (typeof PAYMENT_METHODS)[number]

/** Where a charge came from. `lease` and `recurring` charges are posted by reconciliation. */
export type ChargeSource = 'lease' | 'recurring' | 'manual' | 'late-fee'
export type ExpenseSource = 'work-order' | 'manual' | 'operating'

/** Money owed to the owner (a receivable). */
export interface Charge {
  /** Rent: `chg_<leaseId>_<period>`; recurring: `chg_<recurringId>_<period>`; others random. */
  id: string
  /** Human number, e.g. "INC-10421". */
  reference: string
  category: IncomeCategory
  source: ChargeSource
  /** Tenant charges; the tenant comes from the lease. */
  leaseId?: string
  recurringId?: string
  /** Late fees: the late charge. */
  parentChargeId?: string
  /** Snapshots: a lease can later move to another unit. */
  propertyId: string
  unitId?: string
  /** Non-tenant income, e.g. a laundry operator. */
  payerName?: string
  /** Billing month for lease and recurring charges. */
  period?: string
  description?: string
  amountCents: number
  issuedOn: string
  dueDate: string
  /** Set when the amount was changed by hand; reconciliation never changes it again. */
  adjusted?: true
  voidedAt?: string
  voidReason?: string
  voidedBy?: 'user' | 'system'
  /** Fictional record generated by the demo seed or migration. */
  demo?: true
  createdAt: string
  updatedAt?: string
}

/** Money received against one charge. Never edited: voided with a reason instead. */
export interface Payment {
  id: string
  /** e.g. "PAY-20418". */
  reference: string
  chargeId: string
  amountCents: number
  receivedOn: string
  method: PaymentMethod
  /** Check number, bank reference or a future gateway id. */
  externalRef?: string
  note?: string
  voidedAt?: string
  voidReason?: string
  demo?: true
  createdAt: string
}

/** Money owed by the owner (a bill). Paid in full in v0.8. */
export interface Expense {
  /** Work-order bills: `exp_<workOrderId>`; others random or seeded. */
  id: string
  /** e.g. "EXP-30112". */
  reference: string
  category: ExpenseCategory
  source: ExpenseSource
  workOrderId?: string
  requestId?: string
  vendorId?: string
  /** Payee when it isn't a vendor in Propwise. */
  payeeName?: string
  propertyId: string
  unitId?: string
  description: string
  invoiceNumber?: string
  /** Work-order bills: the work order's estimate at the time the bill was created. */
  estimatedCents?: number
  /** Work-order bills: the work order's final cost. Never changed afterwards. */
  amountCents: number
  billDate: string
  dueDate: string
  paidOn?: string
  paymentMethod?: PaymentMethod
  paymentRef?: string
  voidedAt?: string
  voidReason?: string
  demo?: true
  createdAt: string
  updatedAt?: string
}

/** Finance-owned monthly schedule for non-rent income tied to a lease. */
export interface RecurringCharge {
  id: string
  leaseId: string
  category: RecurringCategory
  description: string
  amountCents: number
  /** Inclusive. */
  startPeriod: string
  /** Inclusive; the schedule also stops when the lease ends. */
  endPeriod?: string
  demo?: true
  createdAt: string
  updatedAt?: string
}

export const FINANCE_EVENT_KINDS = [
  'created',
  'edited',
  'payment-voided',
  'adjusted',
  'voided',
  'marked-paid',
  'marked-unpaid',
  'late-fee-added',
  'auto-adjusted',
  'auto-voided',
  'recurring-ended',
] as const
export type FinanceEventKind = (typeof FINANCE_EVENT_KINDS)[number]

/** Activity history for finance records. Automatic changes are recorded with actor `system` and a reason. */
export interface FinanceEvent {
  id: string
  recordType: 'charge' | 'expense' | 'recurring'
  recordId: string
  kind: FinanceEventKind
  actor: 'user' | 'system'
  title: string
  description: string
  reason?: string
  amountCents?: number
  paymentId?: string
  demo?: true
  createdAt: string
}

/** Records the seed or migration treated as fictional demo data. */
export interface FinanceDemoScope {
  leaseIds: string[]
  propertyIds: string[]
  workOrderIds: string[]
}

export interface FinanceSettings {
  /** ISO 4217 code with two minor digits, e.g. "USD". */
  currency: string
  /** BCP 47 locale used for money formatting. */
  locale: string
  /** First month Finance tracks; fixed when the data was seeded or migrated. */
  startPeriod: string
  /** Days after the due date before a late fee can be added. */
  graceDays: number
  lateFee: { residentialCents: number; commercialPercent: number }
  /** Default days from bill date to due date for new bills. */
  paymentTermsDays: number
  demoScope: FinanceDemoScope
  /** When the seed or migration created the finance data. */
  createdAt: string
}
